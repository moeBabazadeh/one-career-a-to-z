// Every protocol and field the dissectors produce, with its type. The display filter checks names
// and parses literals against this table, the completer offers from it, and the status bar names
// the selected field from it. Abbreviations follow the real ones engineers already type.

export type FieldType =
  'proto' | 'none' | 'u' | 'i' | 'bool' | 'ipv4' | 'ether' | 'str' | 'bytes' | 'f';

export interface FieldDef {
  abbrev: string;
  name: string;
  type: FieldType;
  /** Shown in hex when applied as a filter, at this many digits. */
  hex?: number;
  /** Value names a filter may use instead of numbers. */
  enums?: Record<string, number>;
}

const TYPE_NAMES: Record<FieldType, string> = {
  proto: 'Protocol',
  none: 'Label',
  u: 'Unsigned integer',
  i: 'Signed integer',
  bool: 'Boolean',
  ipv4: 'IPv4 address',
  ether: 'Ethernet or other MAC address',
  str: 'Character string',
  bytes: 'Byte sequence',
  f: 'Floating point (seconds or units)',
};

export const typeName = (t: FieldType) => TYPE_NAMES[t];

