export const FIELDS = new Map<string, FieldDef>(
  ROWS.map(([abbrev, name, type, hex, enums]) => [
    abbrev,
    { abbrev, name, type, ...(hex ? { hex } : {}), ...(enums ? { enums } : {}) },
  ]),
);

/** Aliases a visitor might reach for first: `ble` is the link layer, `att` the attribute protocol. */
export const ALIASES: Record<string, string> = {
  ble: 'btle',
  att: 'btatt',
  l2cap: 'btl2cap',
  modbus_tcp: 'mbtcp',
};

/** A field by name, aliases followed. */
export function lookup(name: string): FieldDef | undefined {
  const direct = FIELDS.get(name);
  if (direct) return direct;
  const dot = name.indexOf('.');
  const head = dot < 0 ? name : name.slice(0, dot);
  const alias = ALIASES[head];
  return alias ? FIELDS.get(alias + (dot < 0 ? '' : name.slice(dot))) : undefined;
}

export const canonical = (name: string) => lookup(name)?.abbrev ?? name;

export const ALL_FIELDS = [...FIELDS.values()];
